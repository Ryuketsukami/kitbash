/** electron-builder.json — MSIX (appx) packaging config. */
export function electronBuilderConfig(cfg: ShipConfig): string {
  const config = {
    appId: cfg.appId,
    productName: cfg.appName,
    // Keep packaging output out of the web build directory.
    directories: { output: 'dist-electron' },
    files: [`${cfg.webDir}/**/*`, 'electron/**/*'],
    win: { target: ['appx'] },
    appx: {
      // These MUST match your Partner Center app identity exactly, or the Store upload is rejected.
      identityName: cfg.windows?.identityName ?? cfg.appId,
      publisherDisplayName: cfg.windows?.publisherDisplayName ?? cfg.appName,
      publisher: cfg.windows?.publisher ?? `CN=${cfg.appName}`,
    },
  };
  return `${JSON.stringify(config, null, 2)}\n`;
}

