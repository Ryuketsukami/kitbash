/** public/sw.js — no-op cache-shell service worker (presence makes the app installable). */
export function serviceWorker(): string {
  return `// Generated by kitbash-ship — minimal no-op service worker shell.
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', () => {
  // Intentionally empty: requests fall through to the network. Add caching here when needed.
});
`;
}

/** src/kitbash-sw.ts — registration snippet for the user's app entry. */
export function swRegister(): string {
  return `// Generated by kitbash-ship — call registerSW() once from your app entry (e.g. main.tsx).
export function registerSW(): void {
  if (!('serviceWorker' in navigator)) return;
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch((error: unknown) => {
      console.warn('[kitbash] service worker registration failed', error);
    });
  });
}
`;
}
