import type { ShipConfig } from '../config.js';

// JSON.stringify gives safe quoting/escaping for values interpolated into generated code.
function q(value: string): string {
  return JSON.stringify(value);
}

/** capacitor.config.ts for the user's app. */
export function capacitorConfig(cfg: ShipConfig): string {
  const deepLink =
    cfg.deepLinkScheme === undefined
      ? ''
      : `
// Deep links (${cfg.deepLinkScheme}://): handle opens with the Capacitor App plugin ('appUrlOpen' event)
// and register the scheme in the native projects — iOS Info.plist CFBundleURLTypes,
// Android intent-filter. See https://capacitorjs.com/docs/apis/app`;
  const server =
    cfg.devUrl === undefined
      ? ''
      : `
  // Dev-only: loads the app from the Vite dev server. Remove \`server\` for release builds.
  server: {
    url: ${q(cfg.devUrl)},${cfg.devUrl.startsWith('http://') ? '\n    cleartext: true,' : ''}
  },`;
  return `import type { CapacitorConfig } from '@capacitor/cli';
${deepLink}
const config: CapacitorConfig = {
  appId: ${q(cfg.appId)},
  appName: ${q(cfg.appName)},
  webDir: ${q(cfg.webDir)},${server}
};

export default config;
`;
}

/** electron/main.mjs — Electron main process for the Microsoft Store shell. */
export function electronMain(cfg: ShipConfig): string {
  const width = cfg.electron?.width ?? 1280;
  const height = cfg.electron?.height ?? 800;
  // loadFile paths resolve relative to the app root, so this works both unpacked and inside app.asar.
  const loadFile = `win.loadFile(join(${q(cfg.webDir)}, 'index.html'));`;
  const load =
    cfg.devUrl === undefined
      ? `  ${loadFile}`
      : `  if (process.env.ELECTRON_DEV === '1') {
    win.loadURL(${q(cfg.devUrl)});
  } else {
    ${loadFile}
  }`;
  return `// Generated by kitbash-ship — Electron main process.
import { app, BrowserWindow } from 'electron';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

function createWindow() {
  const win = new BrowserWindow({
    width: ${width},
    height: ${height},
    webPreferences: {
      contextIsolation: true,
      // ESM (.mjs) preload scripts require an unsandboxed renderer.
      sandbox: false,
      preload: join(here, 'preload.mjs'),
    },
  });
${load}
}

app.whenReady().then(createWindow);

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});

app.on('activate', () => {
  if (BrowserWindow.getAllWindows().length === 0) createWindow();
});
`;
}

